# L5 — Quality / Evidence / Distinct Value

**Date:** 2026-08-20  
**Input:** 167 L4-relevant qualification units  
**Status:** COMPLETE ✅

## Purpose

L5 evaluated whether each opportunity is sufficiently credible, evidence-supported, and distinctive within its opportunity type.

L5 deliberately did not repeat L4 relevance assessment.

A scientifically excellent opportunity can have weak Neuro-TMR relevance.

Likewise, a highly relevant opportunity can still have weak evidence or little distinct value.

---

## Type-Specific Evaluation

### Scientific Collaboration

Evaluated:

- relevant scientific track record,
- methodological depth,
- active capability,
- research environment,
- specialized expertise,
- and unique contribution.

No arbitrary publication-count threshold was used.

### Data / Infrastructure

Evaluated:

- dataset quality,
- annotations,
- modalities,
- reference standards,
- population/sample characteristics,
- access infrastructure,
- and distinct Path V role.

### Funding

Evaluated:

- programme credibility,
- scale,
- mechanism,
- scientific fit,
- leverage,
- and distinct funding function.

Eligibility and timing were not re-scored because they belong primarily to L3/L6.

### Fellowships / Placements

Evaluated:

- research environment,
- mentorship,
- scientific depth,
- duration/mechanism,
- and distinct training or placement value.

### Hardware / Industry

Evaluated:

- physiological-signal quality,
- raw-data capability,
- real-time capability,
- SDK/API or research integration,
- validation evidence,
- sleep suitability,
- and technical distinctiveness.

### Networks

Evaluated:

- concentration of relevant scientists / engineers,
- real networking mechanisms,
- mentorship,
- scientific or industrial connections,
- and distinct downstream access.

### Governance

Evaluated:

- authority,
- institutional legitimacy,
- jurisdictional relevance,
- research-governance function,
- and distinct enabling role.

### Future-Horizon Technologies

Evaluated:

- scientific evidence,
- maturity,
- reproducibility,
- open resources,
- technical plausibility,
- and uniqueness of the proposed capability.

---

## Controlled Research Depth

The existing L2-verified and L4-classified Opportunity Universe was used as the primary evidence base.

Deep research was not repeated for all opportunities.

Additional research was used when:

- evidence maturity was uncertain,
- emerging technology claims required clarification,
- distinctiveness was unclear,
- or a status could materially change.

This kept the qualification process bounded while preserving rigor.

