## Important Interpretation

L5 status is independent from L4 relevance.

Examples:

- a globally strong scientist may still have weak Neuro-TMR relevance;
- a future technology may be highly distinctive but only conditionally relevant;
- a directly relevant technology may still have weak validation;
- a broadly useful network may be credible but redundant.

This separation prevents prestige, relevance, and evidence maturity from being collapsed into a single subjective judgment.

