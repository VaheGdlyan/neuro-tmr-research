## Low-Value Cases

### OPP-048

**Status:** `L5_LOW_VALUE`

The institution is legitimate, but the identified contribution is broad and adds little distinct capability beyond stronger Armenian scientific, training, institutional, and networking opportunities.

### OPP-063

**Status:** `L5_LOW_VALUE`

The individual represents a valid Armenian neuroscience bridge, but the currently identifiable contribution is general and adds limited distinct value beyond stronger diaspora opportunities already present.

These statuses are portfolio judgments, not judgments of the institutions or researchers' general scientific quality.

---

## Useful / Redundant Group

`L5_USEFUL_REDUNDANT` does not mean duplicate.

All such opportunities survived L1 as distinct entities.

The status means that the **function they provide** substantially overlaps with another available mechanism.

This distinction will matter in L6 because strategic actionability depends partly on whether investing effort in an opportunity adds something that cannot be obtained more efficiently elsewhere.

---

## L5 Attrition Decision

No automatic attrition was applied at L5.

This preserves the boundary between:

**L5 — Is the opportunity strong/evidence-supported/distinct?**

and:

**L6 — Is it strategically worth acting on?**

All 167 units therefore proceed to L6 with their L3, L4, and L5 evidence attached.

